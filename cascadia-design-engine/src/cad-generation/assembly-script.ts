/**
 * Assembly Script Generator
 *
 * Serializes an assembly plan to a FreeCAD Python script that reads each
 * child STEP file, applies its placement transform, and collects the result
 * into one compound. The script is the plan's portable, human-readable form
 * and is kept on the BOM node as `assemblyComposition.assemblyScript`; the
 * geometry itself is rendered by the `generation.cad.assemble` worker from
 * the same placements, so the two can never disagree about a transform.
 *
 * Rotation convention (pinned by `cascadia-workers-cad-generator/tests/test_assembly.py`):
 * rotateX → rotateY → rotateZ, each about the GLOBAL axis through the origin,
 * in degrees, followed by translation. `place()` below applies exactly that
 * sequence, so running the script in FreeCAD reproduces the worker's output.
 */

import type { AssemblyPlan } from './types'

export interface AssemblyScript {
  /** The full script text. */
  source: string
  /** The `name` each child was bound to, keyed by tempId. */
  variableNames: Map<string, string>
}

/** Format a number for Python source: integers stay integers. */
function num(value: number): string {
  if (!Number.isFinite(value)) return '0'
  return Number.isInteger(value)
    ? String(value)
    : String(Number(value.toFixed(6)))
}

/**
 * Sanitize a part name into a valid, unique Python identifier.
 */
function toIdentifier(name: string, taken: Set<string>): string {
  let base = name
    .replace(/[^a-zA-Z0-9_]/g, '_')
    .replace(/__+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toLowerCase()
  if (base.length === 0) base = 'part'
  if (/^[0-9]/.test(base)) base = `part_${base}`
  if (PYTHON_RESERVED.has(base)) base = `${base}_part`

  let candidate = base
  let suffix = 2
  while (taken.has(candidate)) {
    candidate = `${base}_${suffix}`
    suffix++
  }
  taken.add(candidate)
  return candidate
}

const PYTHON_RESERVED = new Set([
  'and',
  'as',
  'assert',
  'break',
  'class',
  'continue',
  'def',
  'del',
  'elif',
  'else',
  'except',
  'finally',
  'for',
  'from',
  'global',
  'if',
  'import',
  'in',
  'is',
  'lambda',
  'nonlocal',
  'not',
  'or',
  'pass',
  'raise',
  'return',
  'try',
  'while',
  'with',
  'yield',
  'doc',
  'place',
  'result',
  'shapes',
])

/** Comment-safe single line: no newlines, so a name cannot break out of a `#`. */
function commentLine(text: string): string {
  return text.replace(/\s+/g, ' ').trim()
}

/**
 * Generate the FreeCAD assembly script for a plan.
 */
export function generateAssemblyScript(
  plan: AssemblyPlan,
  assemblyName?: string,
): AssemblyScript {
  const taken = new Set<string>()
  const variableNames = new Map<string, string>()
  const lines: Array<string> = []

  lines.push(`# Assembly: ${commentLine(assemblyName ?? plan.assemblyTempId)}`)
  lines.push(
    '# Auto-generated by Cascadia Design Engine — FreeCAD 1.x, headless-safe.',
  )
  if (plan.reasoning.trim().length > 0) {
    lines.push('#')
    for (const paragraph of plan.reasoning.split(/\r?\n/)) {
      const clean = commentLine(paragraph)
      if (clean) lines.push(`# ${clean}`)
    }
  }
  lines.push('#')
  lines.push(
    '# Each child is referenced by its Cascadia vault file id. Export the',
  )
  lines.push(
    '# children from the vault as <id>.step in the working directory first.',
  )
  lines.push('')
  lines.push('import FreeCAD as App')
  lines.push('import Part')
  lines.push('from FreeCAD import Base')
  lines.push('')
  lines.push('')
  lines.push('def place(shape, rx, ry, rz, tx, ty, tz):')
  lines.push(
    '    """rotateX -> rotateY -> rotateZ about the global origin (degrees),',
  )
  lines.push(
    '    then translate -- the convention the generation.cad.assemble worker',
  )
  lines.push('    applies, so this script reproduces its output."""')
  lines.push('    origin = Base.Vector(0, 0, 0)')
  lines.push('    if rx:')
  lines.push('        shape.rotate(origin, Base.Vector(1, 0, 0), rx)')
  lines.push('    if ry:')
  lines.push('        shape.rotate(origin, Base.Vector(0, 1, 0), ry)')
  lines.push('    if rz:')
  lines.push('        shape.rotate(origin, Base.Vector(0, 0, 1), rz)')
  lines.push('    if tx or ty or tz:')
  lines.push('        shape.translate(Base.Vector(tx, ty, tz))')
  lines.push('    return shape')
  lines.push('')
  lines.push('')
  lines.push(
    `doc = App.newDocument(${pyString(toIdentifier(assemblyName ?? plan.assemblyTempId, new Set()))})`,
  )
  lines.push('shapes = []')
  lines.push('')

  for (const placement of plan.placements) {
    const varName = toIdentifier(placement.partName, taken)
    variableNames.set(placement.tempId, varName)
    const { translation: t, rotation: r } = placement.transform

    lines.push(
      `# ${commentLine(placement.partName)} (tempId ${placement.tempId})`,
    )
    lines.push(
      `${varName} = place(Part.read(${pyString(`${placement.stepFileKey}.step`)}), ` +
        `${num(r.x)}, ${num(r.y)}, ${num(r.z)}, ${num(t.x)}, ${num(t.y)}, ${num(t.z)})`,
    )
    lines.push(
      `${varName}_obj = doc.addObject("Part::Feature", ${pyString(varName)})`,
    )
    lines.push(`${varName}_obj.Shape = ${varName}`)
    lines.push(`shapes.append(${varName})`)

    if (placement.quantity > 1) {
      lines.push(
        `# quantity ${placement.quantity}: the plan carries one transform per placement, so`,
      )
      lines.push(
        '# the additional instances are not positioned here (same gap as the worker).',
      )
    }
    lines.push('')
  }

  lines.push('doc.recompute()')
  lines.push('result = Part.makeCompound(shapes)')
  lines.push('')

  return { source: lines.join('\n'), variableNames }
}

/** A double-quoted Python string literal. */
function pyString(value: string): string {
  return JSON.stringify(value)
}
